// Copies the pure state machine into the browser demo. The copy is generated, never edited.
// `node scripts/sync-demo.mjs` writes it. `node scripts/sync-demo.mjs --check` fails if it drifted.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('../', import.meta.url));
export const header = '// GENERATED from core/machine.js by scripts/sync-demo.mjs. Do not edit this file.\n';
export const files = [['core/machine.js', 'demo/lib/machine.js'], ['public/vision-quest.js', 'demo/lib/vision-quest.js']];

export const expected = (root, source) => header + readFileSync(join(root, source), 'utf8');

// Returns the list of generated files that are missing or differ from their source.
export function drifted(root = here) {
  return files.filter(([source, target]) => {
    const path = join(root, target);
    return !existsSync(path) || readFileSync(path, 'utf8') !== expected(root, source);
  }).map(([, target]) => target);
}

export function sync(root = here) {
  for (const [source, target] of files) {
    mkdirSync(dirname(join(root, target)), { recursive: true });
    writeFileSync(join(root, target), expected(root, source));
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const bad = drifted();
    if (bad.length) {
      console.error(`demo copy has drifted: ${bad.join(', ')}. Run: node scripts/sync-demo.mjs`);
      process.exitCode = 1;
    } else console.log('demo copy matches core/machine.js');
  } else {
    sync();
    console.log('wrote demo/lib/machine.js');
  }
}
